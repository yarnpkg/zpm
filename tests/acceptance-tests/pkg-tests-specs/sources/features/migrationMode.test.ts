import {Filename, PortablePath, ppath, xfs} from '@yarnpkg/fslib';

const {
  tests: {setPackageWhitelist, testIf},
} = require(`pkg-tests-core`);

const MIGRATION_LOCKFILE = `.yarn/ignore/migration/yarn.lock` as PortablePath;

// Files that the Yarn release the project is migrating from (here Yarn 4)
// relies on; the migration mode must never touch them
const MAINSTREAM_FILES = [
  Filename.lockfile,
  Filename.rc,
  Filename.manifest,
];

const MIGRATION_MODE = {
  enableMigrationMode: true,
};

const BERRY_RC = [
  `nodeLinker: pnp\n`,
  `enableTelemetry: false\n`,
].join(``);

const makeBerryLockfile = ({noDepsVersion = `1.0.0`}: {noDepsVersion?: string} = {}) => [
  `# This file is generated by running "yarn install" inside your project.\n`,
  `# Manual changes might be lost - proceed with caution!\n`,
  `\n`,
  `__metadata:\n`,
  `  version: 8\n`,
  `  cacheKey: 10c0\n`,
  `\n`,
  `"migration-root@workspace:.":\n`,
  `  version: 0.0.0-use.local\n`,
  `  resolution: "migration-root@workspace:."\n`,
  `  dependencies:\n`,
  `    one-range-dep: "npm:1.0.0"\n`,
  `  languageName: unknown\n`,
  `  linkType: soft\n`,
  `\n`,
  `"no-deps@npm:^1.0.0":\n`,
  `  version: ${noDepsVersion}\n`,
  `  resolution: "no-deps@npm:${noDepsVersion}"\n`,
  `  languageName: node\n`,
  `  linkType: hard\n`,
  `\n`,
  `"one-range-dep@npm:1.0.0":\n`,
  `  version: 1.0.0\n`,
  `  resolution: "one-range-dep@npm:1.0.0"\n`,
  `  dependencies:\n`,
  `    no-deps: "npm:^1.0.0"\n`,
  `  languageName: node\n`,
  `  linkType: hard\n`,
].join(``);

const manifest = {
  name: `migration-root`,
  dependencies: {
    [`one-range-dep`]: `1.0.0`,
  },
};

async function setupBerryProject(path: PortablePath) {
  await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile());
  await xfs.writeFilePromise(ppath.join(path, Filename.rc), BERRY_RC);
}

async function readMainstreamFiles(path: PortablePath) {
  const files: Record<string, string> = {};

  for (const file of MAINSTREAM_FILES)
    files[file] = await xfs.readFilePromise(ppath.join(path, file), `utf8`);

  return files;
}

async function readMigrationLockfile(path: PortablePath) {
  return await xfs.readFilePromise(ppath.join(path, MIGRATION_LOCKFILE), `utf8`);
}

describe(`Features`, () => {
  describe(`Migration Mode`, () => {
    test(
      `it should install a project with a Berry lockfile, writing the lockfile in the migration folder`,
      makeTemporaryEnv(manifest, async ({path, run, source}) => {
        await setupBerryProject(path);

        const before = await readMainstreamFiles(path);

        await run(`install`, MIGRATION_MODE);

        await expect(readMainstreamFiles(path)).resolves.toEqual(before);

        // The migration lockfile uses the format of the Yarn release we're migrating to
        expect(JSON.parse(await readMigrationLockfile(path))).toMatchObject({
          __metadata: expect.anything(),
        });

        // The local cache is disabled in migration mode, even though the
        // test environment sets `enableGlobalCache: false`
        expect(xfs.existsSync(ppath.join(path, `.yarn/cache`))).toEqual(false);

        // The resolutions from the Berry lockfile are kept (no-deps@1.1.0
        // would otherwise be selected)
        await expect(source(`require('one-range-dep')`, MIGRATION_MODE)).resolves.toMatchObject({
          version: `1.0.0`,
          dependencies: {
            [`no-deps`]: {
              version: `1.0.0`,
            },
          },
        });
      }),
    );

    test(
      `it should create the migration folder when it doesn't exist yet`,
      makeTemporaryEnv(manifest, async ({path, run}) => {
        await run(`install`, MIGRATION_MODE);

        expect(xfs.existsSync(ppath.join(path, MIGRATION_LOCKFILE))).toEqual(true);
        expect(xfs.existsSync(ppath.join(path, Filename.lockfile))).toEqual(false);
      }),
    );

    test(
      `it should install a project with a Berry lockfile using the node-modules linker`,
      makeTemporaryEnv(manifest, async ({path, run, source}) => {
        await setupBerryProject(path);
        await xfs.writeFilePromise(ppath.join(path, Filename.rc), `nodeLinker: node-modules\n`);

        const before = await readMainstreamFiles(path);

        await run(`install`, MIGRATION_MODE);

        await expect(readMainstreamFiles(path)).resolves.toEqual(before);
        expect(xfs.existsSync(ppath.join(path, MIGRATION_LOCKFILE))).toEqual(true);

        await expect(xfs.readJsonPromise(ppath.join(path, `node_modules/no-deps/package.json`))).resolves.toMatchObject({
          version: `1.0.0`,
        });
      }),
    );

    test(
      `it should consider the project up-to-date after a first install`,
      makeTemporaryEnv(manifest, async ({path, run}) => {
        await setupBerryProject(path);

        await run(`install`, MIGRATION_MODE);

        const migrationLockfile = await readMigrationLockfile(path);

        await expect(run(`install`, MIGRATION_MODE)).resolves.toMatchObject({
          stdout: expect.stringContaining(`All dependencies are up-to-date, nothing to do.`),
        });

        await expect(readMigrationLockfile(path)).resolves.toEqual(migrationLockfile);
      }),
    );

    test(
      `it should pick up changes made to the main lockfile by other contributors`,
      makeTemporaryEnv(manifest, async ({path, run, source}) => {
        await setupBerryProject(path);

        await run(`install`, MIGRATION_MODE);

        // Someone else upgraded the dependency using the mainstream Yarn release
        await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile({noDepsVersion: `1.0.1`}));

        await run(`install`, MIGRATION_MODE);

        await expect(source(`require('one-range-dep')`, MIGRATION_MODE)).resolves.toMatchObject({
          dependencies: {
            [`no-deps`]: {
              version: `1.0.1`,
            },
          },
        });
      }),
    );

    test(
      `it should update the migration lockfile but not the main one when adding and removing dependencies`,
      makeTemporaryEnv(manifest, async ({path, run}) => {
        await setupBerryProject(path);

        await run(`install`, MIGRATION_MODE);

        const mainLockfile = await xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`);

        await run(`add`, `no-deps-bins@1.0.0`, MIGRATION_MODE);

        await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(mainLockfile);
        await expect(readMigrationLockfile(path)).resolves.toContain(`no-deps-bins@npm:1.0.0`);

        await run(`remove`, `no-deps-bins`, MIGRATION_MODE);

        await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(mainLockfile);
        await expect(readMigrationLockfile(path)).resolves.not.toContain(`no-deps-bins`);
      }),
    );

    test(
      `it should lazily install the dependencies when running a script after a manifest change`,
      makeTemporaryEnv({
        ...manifest,
        scripts: {
          [`print`]: `node -p "require('no-deps-bins/package.json').version"`,
        },
      }, async ({path, run}) => {
        await setupBerryProject(path);

        const mainLockfile = await xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`);

        await run(`install`, MIGRATION_MODE);

        await xfs.writeJsonPromise(ppath.join(path, Filename.manifest), {
          ...await xfs.readJsonPromise(ppath.join(path, Filename.manifest)),
          dependencies: {
            [`no-deps-bins`]: `1.0.0`,
            [`one-range-dep`]: `1.0.0`,
          },
        });

        await expect(run(`run`, `print`, MIGRATION_MODE)).resolves.toMatchObject({
          stdout: `1.0.0\n`,
        });

        await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(mainLockfile);
        await expect(readMigrationLockfile(path)).resolves.toContain(`no-deps-bins@npm:1.0.0`);
      }),
    );

    test(
      `it should allow immutable installs to create the migration lockfile when the main lockfile is up-to-date`,
      makeTemporaryEnv(manifest, async ({path, run}) => {
        await setupBerryProject(path);

        const before = await readMainstreamFiles(path);

        await run(`install`, `--immutable`, MIGRATION_MODE);

        await expect(readMainstreamFiles(path)).resolves.toEqual(before);
        expect(xfs.existsSync(ppath.join(path, MIGRATION_LOCKFILE))).toEqual(true);

        await run(`install`, `--immutable`, MIGRATION_MODE);
      }),
    );

    test(
      `it should allow immutable installs to refresh the migration lockfile after the main lockfile changed`,
      makeTemporaryEnv(manifest, async ({path, run, source}) => {
        await setupBerryProject(path);

        await run(`install`, MIGRATION_MODE);

        await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile({noDepsVersion: `1.0.1`}));

        await run(`install`, `--immutable`, MIGRATION_MODE);

        await expect(source(`require('one-range-dep')`, MIGRATION_MODE)).resolves.toMatchObject({
          dependencies: {
            [`no-deps`]: {
              version: `1.0.1`,
            },
          },
        });
      }),
    );

    test(
      `it should reject immutable installs that would add resolutions`,
      makeTemporaryEnv(manifest, async ({path, run}) => {
        await setupBerryProject(path);

        await run(`install`, MIGRATION_MODE);

        const migrationLockfile = await readMigrationLockfile(path);

        await xfs.writeJsonPromise(ppath.join(path, Filename.manifest), {
          ...await xfs.readJsonPromise(ppath.join(path, Filename.manifest)),
          dependencies: {
            [`no-deps-bins`]: `1.0.0`,
            [`one-range-dep`]: `1.0.0`,
          },
        });

        const before = await readMainstreamFiles(path);

        await expect(run(`install`, `--immutable`, MIGRATION_MODE)).rejects.toThrow(/The lockfile would have been modified by this install/);

        await expect(readMainstreamFiles(path)).resolves.toEqual(before);
        await expect(readMigrationLockfile(path)).resolves.toEqual(migrationLockfile);
      }),
    );

    test(
      `it should reject immutable installs that would create the migration lockfile with new resolutions`,
      makeTemporaryEnv({
        ...manifest,
        dependencies: {
          [`no-deps-bins`]: `1.0.0`,
          [`one-range-dep`]: `1.0.0`,
        },
      }, async ({path, run}) => {
        await setupBerryProject(path);

        await expect(run(`install`, `--immutable`, MIGRATION_MODE)).rejects.toThrow(/The lockfile would have been created by this install/);

        expect(xfs.existsSync(ppath.join(path, MIGRATION_LOCKFILE))).toEqual(false);
      }),
    );

    test(
      `it should install a project whose main lockfile already uses the current format`,
      makeTemporaryEnv(manifest, async ({path, run, source}) => {
        await setPackageWhitelist(new Map([
          [`no-deps`, new Set([`1.0.0`])],
        ]), async () => {
          await run(`install`);
        });

        const mainLockfile = await xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`);

        await run(`install`, MIGRATION_MODE);

        await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(mainLockfile);
        expect(xfs.existsSync(ppath.join(path, MIGRATION_LOCKFILE))).toEqual(true);

        await expect(source(`require('one-range-dep')`, MIGRATION_MODE)).resolves.toMatchObject({
          dependencies: {
            [`no-deps`]: {
              version: `1.0.0`,
            },
          },
        });

        await run(`install`, `--immutable`, MIGRATION_MODE);
      }),
    );

    test(
      `it should convert the main lockfile once the migration mode is turned off`,
      makeTemporaryEnv(manifest, async ({path, run, source}) => {
        await setupBerryProject(path);

        await run(`install`, MIGRATION_MODE);
        await run(`add`, `no-deps-bins@1.0.0`, MIGRATION_MODE);

        await run(`install`);

        const mainLockfile = await xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`);

        // The main lockfile is now in the current format, and keeps the
        // resolutions from the Berry lockfile
        expect(JSON.parse(mainLockfile)).toMatchObject({
          __metadata: expect.anything(),
        });

        expect(mainLockfile).toContain(`no-deps-bins@npm:1.0.0`);

        await expect(source(`require('one-range-dep')`)).resolves.toMatchObject({
          dependencies: {
            [`no-deps`]: {
              version: `1.0.0`,
            },
          },
        });

        await run(`install`, `--immutable`);
      }),
    );

    describe(`Yarn Switch`, () => {
      // These tests run the fake Yarn releases served by the test registry,
      // which Windows can't execute (see `runnableFakeYarnRelease`)
      const switchManifest = {
        packageManager: `yarn@6.0.0`,
        packageManagerMigration: `yarn@6.1.0`,
      };

      testIf(
        `runnableFakeYarnRelease`,
        `it should run the migration version once the project is linked to it`,
        makeTemporaryEnv(switchManifest, async ({runSwitch}) => {
          await expect(runSwitch(`--version`)).resolves.toMatchObject({
            stdout: expect.stringContaining(`Fake Yarn 6.0.0`),
          });

          await runSwitch(`switch`, `link`, `--migration`);

          await expect(runSwitch(`--version`)).resolves.toMatchObject({
            stdout: expect.stringContaining(`Fake Yarn 6.1.0`),
          });

          await runSwitch(`switch`, `unlink`);

          await expect(runSwitch(`--version`)).resolves.toMatchObject({
            stdout: expect.stringContaining(`Fake Yarn 6.0.0`),
          });
        }),
      );

      testIf(
        `runnableFakeYarnRelease`,
        `it should run the mainstream version when the migration mode is explicitly disabled`,
        makeTemporaryEnv(switchManifest, async ({runSwitch}) => {
          await runSwitch(`switch`, `link`, `--migration`);

          await expect(runSwitch(`--version`, {env: {YARN_ENABLE_MIGRATION_MODE: `0`}})).resolves.toMatchObject({
            stdout: expect.stringContaining(`Fake Yarn 6.0.0`),
          });

          // The link is kept for the next commands
          await expect(runSwitch(`--version`)).resolves.toMatchObject({
            stdout: expect.stringContaining(`Fake Yarn 6.1.0`),
          });
        }),
      );

      testIf(
        `runnableFakeYarnRelease`,
        `it should unlink the migration once the packageManagerMigration field is removed`,
        makeTemporaryEnv(switchManifest, async ({path, runSwitch}) => {
          await runSwitch(`switch`, `link`, `--migration`);

          await xfs.writeJsonPromise(ppath.join(path, Filename.manifest), {
            packageManager: `yarn@6.1.0`,
          });

          await expect(runSwitch(`--version`)).resolves.toMatchObject({
            stdout: expect.stringContaining(`Fake Yarn 6.1.0`),
          });

          await xfs.writeJsonPromise(ppath.join(path, Filename.manifest), {
            packageManager: `yarn@6.0.0`,
            packageManagerMigration: `yarn@6.1.0`,
          });

          await expect(runSwitch(`--version`)).resolves.toMatchObject({
            stdout: expect.stringContaining(`Fake Yarn 6.0.0`),
          });
        }),
      );

      testIf(
        `runnableFakeYarnRelease`,
        `it should refuse to link a project without a packageManagerMigration field`,
        makeTemporaryEnv({
          packageManager: `yarn@6.0.0`,
        }, async ({runSwitch}) => {
          await expect(runSwitch(`switch`, `link`, `--migration`)).rejects.toMatchObject({
            stdout: expect.stringContaining(`doesn't list a packageManagerMigration field`),
          });

          await expect(runSwitch(`--version`)).resolves.toMatchObject({
            stdout: expect.stringContaining(`Fake Yarn 6.0.0`),
          });
        }),
      );
    });
  });
});
