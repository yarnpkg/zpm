import {execUtils}                   from '@yarnpkg/core';
import {Filename, npath, ppath, xfs} from '@yarnpkg/fslib';
import {tests}                       from 'pkg-tests-core';

const makeBerryLockfile = (version: number, entries: Array<string> = []) => [
  `# This file is generated by running "yarn install" inside your project.\n`,
  `# Manual changes might be lost - proceed with caution!\n`,
  `\n`,
  `__metadata:\n`,
  `  version: ${version}\n`,
  `  cacheKey: 0c0\n`,
  ...entries,
].join(``);

const NO_DEPS_ENTRY = [
  `\n`,
  `"no-deps@npm:^1.0.0":\n`,
  `  version: 1.0.0\n`,
  `  resolution: "no-deps@npm:1.0.0"\n`,
  `  checksum: 0c0/af041f19ffad13c40b220f0319b95436c0e886ddb630988d78e35eb3b4e3d64131f1e7e9efa5818a7f3307718e322220bda7676fcc202f1841e587aa079b7205\n`,
  `  languageName: node\n`,
  `  linkType: hard\n`,
];

// The test environment pins these settings to their Yarn 4 values; the
// lockfile migration only kicks in for settings the user hasn't defined.
const WITH_YARN6_DEFAULTS = {
  env: {
    YARN_ENABLE_SCRIPTS: undefined,
    YARN_APPROVED_GIT_REPOSITORIES: undefined,
    YARN_NPM_MINIMAL_AGE_GATE: undefined,
  },
};

describe(`Features`, () => {
  describe(`Berry Lockfile`, () => {
    test(`it should correctly import the lockfile from a Berry install`, makeTemporaryEnv({
      dependencies: {[`no-deps`]: `^1.0.0`},
    }, async ({path, run, source}) => {
      await xfs.writeFilePromise(ppath.join(path, `yarn.lock`), makeBerryLockfile(8, NO_DEPS_ENTRY));

      await run(`install`);

      await expect(source(`require('no-deps')`)).resolves.toMatchObject({
        name: `no-deps`,
        version: `1.0.0`,
      });
    }));

    describe(`Migration rules`, () => {
      for (const command of [`install`, `dedupe`]) {
        test(
          `it should migrate old lockfiles by setting enableScripts and approvedGitRepositories when unset (${command})`,
          makeTemporaryEnv({
            dependencies: {
              [`no-deps`]: `^1.0.0`,
            },
          }, async ({path, run}) => {
            const rcPath = ppath.join(path, Filename.rc);

            await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile(8, NO_DEPS_ENTRY));
            await expect(xfs.existsPromise(rcPath)).resolves.toBeFalsy();

            await run(command, WITH_YARN6_DEFAULTS);

            await expect(xfs.readFilePromise(rcPath, `utf8`)).resolves.toContain(`enableScripts: true`);
            await expect(xfs.readFilePromise(rcPath, `utf8`)).resolves.toMatch(/approvedGitRepositories:\r?\n\s*-\s*['"]?\*\*['"]?/);
          }),
        );
      }

      test(
        `dedupe checks should apply legacy defaults without writing project files`,
        makeTemporaryEnv({
          dependencies: {
            [`release-date`]: `1.1.1`,
          },
        }, async ({path, run}) => {
          const lockfile = makeBerryLockfile(8);
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), lockfile);

          await run(`dedupe`, `--check`, WITH_YARN6_DEFAULTS);

          await expect(xfs.existsPromise(ppath.join(path, Filename.rc))).resolves.toBeFalsy();
          await expect(xfs.existsPromise(ppath.join(path, `.pnp.cjs`))).resolves.toBeFalsy();
          await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(lockfile);
        }),
      );

      test(
        `it should migrate old lockfiles by disabling npmMinimalAgeGate when unset`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run}) => {
          const rcPath = ppath.join(path, Filename.rc);

          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile(9, NO_DEPS_ENTRY));
          await expect(xfs.existsPromise(rcPath)).resolves.toBeFalsy();

          await run(`install`, WITH_YARN6_DEFAULTS);

          // Lockfile v9 was already generated with the new git and script defaults
          await expect(xfs.readFilePromise(rcPath, `utf8`)).resolves.toEqual(`npmMinimalAgeGate: 0s\n`);
        }),
      );

      test(
        `it should write all the settings for a Yarn 4 lockfile and report them`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile(8, NO_DEPS_ENTRY));
          await xfs.writeFilePromise(ppath.join(path, Filename.rc), `# Project settings\nnodeLinker: node-modules # keep me\n`);

          const {stdout} = await run(`install`, WITH_YARN6_DEFAULTS);

          await expect(xfs.readFilePromise(ppath.join(path, Filename.rc), `utf8`)).resolves.toEqual([
            `# Project settings\n`,
            `approvedGitRepositories:\n`,
            `  - "**"\n`,
            `enableScripts: true\n`,
            `nodeLinker: node-modules # keep me\n`,
            `npmMinimalAgeGate: 0s\n`,
          ].join(``));

          expect(stdout).toContain(`The lockfile was generated by an older Yarn release (version 8); the following settings have been added to .yarnrc.yml`);
          expect(stdout).toContain(`approvedGitRepositories: ["**"]`);
          expect(stdout).toContain(`enableScripts: true`);
          expect(stdout).toContain(`npmMinimalAgeGate: 0s`);
        }),
      );

      test(
        `it should apply the settings to the install that performs the migration`,
        makeTemporaryEnv({
          dependencies: {
            [`no-prepack`]: tests.startPackageServer().then(url => `${url}/repositories/no-prepack.git`),
            [`no-deps-scripted`]: `1.0.0`,
            [`release-date`]: `1.1.1`,
          },
        }, async ({path, run, source}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile(8));

          await run(`install`, WITH_YARN6_DEFAULTS);

          await expect(source(`require('no-prepack')`, WITH_YARN6_DEFAULTS)).resolves.toEqual(42);
          await expect(source(`require('no-deps-scripted/log')`, WITH_YARN6_DEFAULTS)).resolves.toEqual([`preinstall`, `install`, `postinstall`]);
          await expect(source(`require('release-date/package.json').version`, WITH_YARN6_DEFAULTS)).resolves.toEqual(`1.1.1`);
        }),
      );

      test(
        `it should leave the settings already defined in the project rc untouched`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile(8, NO_DEPS_ENTRY));
          await xfs.writeFilePromise(ppath.join(path, Filename.rc), `enableScripts: false\napprovedGitRepositories: []\nnpmMinimalAgeGate: 3d\n`);

          const {stdout} = await run(`install`, WITH_YARN6_DEFAULTS);

          await expect(xfs.readFilePromise(ppath.join(path, Filename.rc), `utf8`)).resolves.toEqual(`enableScripts: false\napprovedGitRepositories: []\nnpmMinimalAgeGate: 3d\n`);
          expect(stdout).not.toContain(`older Yarn release`);
        }),
      );

      test(
        `it should leave the settings defined in the home rc or the environment untouched`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile(8, NO_DEPS_ENTRY));
          await xfs.writeFilePromise(ppath.join(ppath.dirname(path), Filename.rc), `approvedGitRepositories: []\n`);

          await run(`install`, {
            env: {
              ...WITH_YARN6_DEFAULTS.env,
              YARN_NPM_MINIMAL_AGE_GATE: `0`,
            },
          });

          await expect(xfs.readFilePromise(ppath.join(path, Filename.rc), `utf8`)).resolves.toEqual(`enableScripts: true\n`);
          await expect(xfs.readFilePromise(ppath.join(ppath.dirname(path), Filename.rc), `utf8`)).resolves.toEqual(`approvedGitRepositories: []\n`);
        }),
      );

      test(
        `it shouldn't do anything for lockfiles generated by recent releases`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile(10, NO_DEPS_ENTRY));

          const {stdout} = await run(`install`, WITH_YARN6_DEFAULTS);

          expect(stdout).not.toContain(`older Yarn release`);
          await expect(xfs.existsPromise(ppath.join(path, Filename.rc))).resolves.toBeFalsy();

          // Now with a lockfile in the current format
          await run(`install`, `--force`, WITH_YARN6_DEFAULTS);

          await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toMatch(/^\{/);
          await expect(xfs.existsPromise(ppath.join(path, Filename.rc))).resolves.toBeFalsy();
        }),
      );

      test(
        `it should only migrate once`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run}) => {
          const rcPath = ppath.join(path, Filename.rc);

          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), makeBerryLockfile(8, NO_DEPS_ENTRY));

          await run(`install`, WITH_YARN6_DEFAULTS);
          const rcContent = await xfs.readFilePromise(rcPath, `utf8`);

          const {stdout} = await run(`install`, WITH_YARN6_DEFAULTS);
          expect(stdout).toContain(`All dependencies are up-to-date`);
          expect(stdout).not.toContain(`older Yarn release`);
          await expect(xfs.readFilePromise(rcPath, `utf8`)).resolves.toEqual(rcContent);

          // Users removing the settings opt into the new defaults
          await xfs.writeFilePromise(rcPath, `enableScripts: true\n`);
          await run(`install`, WITH_YARN6_DEFAULTS);
          await expect(xfs.readFilePromise(rcPath, `utf8`)).resolves.toEqual(`enableScripts: true\n`);
        }),
      );

      test(
        `it shouldn't write the settings when running an immutable install`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run}) => {
          const lockfile = makeBerryLockfile(8, NO_DEPS_ENTRY);
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), lockfile);

          await expect(run(`install`, `--immutable`, WITH_YARN6_DEFAULTS)).rejects.toMatchObject({
            stdout: expect.stringContaining(`immutable installs prevent writing them to .yarnrc.yml`),
          });

          await expect(xfs.existsPromise(ppath.join(path, Filename.rc))).resolves.toBeFalsy();
          await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(lockfile);
        }),
      );

      test(
        `it should apply the settings without writing them under the migration mode`,
        makeTemporaryEnv({
          dependencies: {
            [`no-prepack`]: tests.startPackageServer().then(url => `${url}/repositories/no-prepack.git`),
          },
        }, async ({path, run, source}) => {
          const lockfile = makeBerryLockfile(8);
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), lockfile);

          // TODO: the migration mode doesn't create the folder of its lockfile yet
          await xfs.mkdirPromise(ppath.join(path, `.yarn/ignore/migration`), {recursive: true});

          const migrationEnv = {
            env: {
              ...WITH_YARN6_DEFAULTS.env,
              YARN_ENABLE_MIGRATION_MODE: `1`,
            },
          };

          const {stdout} = await run(`install`, migrationEnv);
          expect(stdout).toContain(`the following settings are used during the migration but won't be written to .yarnrc.yml`);

          await expect(source(`require('no-prepack')`, migrationEnv)).resolves.toEqual(42);

          await expect(xfs.existsPromise(ppath.join(path, Filename.rc))).resolves.toBeFalsy();
          await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(lockfile);

          await expect(run(`install`, migrationEnv)).resolves.toMatchObject({
            stdout: expect.stringContaining(`All dependencies are up-to-date`),
          });
        }),
      );
    });

    test(`it should keep the commits of git:// dependencies pinned when importing the lockfile from a Berry install`, makeTemporaryEnv({
      dependencies: {[`git-pkg`]: `git://git.example.test/git-pkg.git`},
    }, async ({path, run, source}) => {
      const repositoriesPath = await xfs.mktempPromise();
      const repositoryPath = ppath.join(repositoriesPath, `git-pkg.git`);

      const git = async (...args: Array<string>) => {
        const {stdout} = await execUtils.execvp(`git`, [`-c`, `user.name=John Doe`, `-c`, `user.email=john.doe@example.org`, `-c`, `commit.gpgsign=false`, ...args], {cwd: repositoryPath, strict: true});
        return stdout.trim();
      };

      await xfs.mkdirPromise(repositoryPath);
      await git(`init`);

      await xfs.writeJsonPromise(ppath.join(repositoryPath, `package.json`), {name: `git-pkg`, version: `1.0.0`});
      await xfs.writeFilePromise(ppath.join(repositoryPath, `index.js`), `module.exports = 1;\n`);
      await git(`add`, `.`);
      await git(`commit`, `-m`, `First commit`);

      const pinnedCommit = await git(`rev-parse`, `HEAD`);

      // The pinned commit isn't the latest one anymore; re-resolving the
      // dependency instead of using the lockfile would install this one
      await xfs.writeFilePromise(ppath.join(repositoryPath, `index.js`), `module.exports = 2;\n`);
      await git(`commit`, `-am`, `Second commit`);

      await xfs.writeFilePromise(ppath.join(path, `yarn.lock`), [
        `# This file is generated by running "yarn install" inside your project.\n`,
        `# Manual changes might be lost - proceed with caution!\n`,
        `\n`,
        `__metadata:\n`,
        `  version: 8\n`,
        `  cacheKey: 0c0\n`,
        `\n`,
        `"git-pkg@git://git.example.test/git-pkg.git":\n`,
        `  version: 1.0.0\n`,
        `  resolution: "git-pkg@git://git.example.test/git-pkg.git#commit=${pinnedCommit}"\n`,
        `  languageName: node\n`,
        `  linkType: hard\n`,
      ].join(``));

      await run(`install`, {
        env: {
          // Serves the git:// repository from the local folder, so the test
          // doesn't need a git daemon
          GIT_CONFIG_COUNT: `1`,
          GIT_CONFIG_KEY_0: `url.${npath.fromPortablePath(repositoriesPath)}/.insteadOf`,
          GIT_CONFIG_VALUE_0: `git://git.example.test/`,
        },
      });

      await expect(source(`require('git-pkg')`)).resolves.toEqual(1);

      const lockfile = await xfs.readFilePromise(ppath.join(path, `yarn.lock`), `utf8`);
      expect(lockfile).toContain(`"git-pkg@git:git://git.example.test/git-pkg.git#commit=${pinnedCommit}"`);
    }));
  });
});
