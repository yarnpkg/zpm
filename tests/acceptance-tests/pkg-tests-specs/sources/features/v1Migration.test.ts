import {Filename, ppath, xfs} from '@yarnpkg/fslib';
import {tests}                from 'pkg-tests-core';

const V1_HEADER = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n`;

const V1_NO_DEPS_LOCKFILE = `${V1_HEADER}${[
  `no-deps@^1.0.0:`,
  `  version "1.0.0"`,
  `  resolved "https://registry.yarnpkg.com/no-deps/-/no-deps-1.0.0.tgz#0000000000000000000000000000000000000000"`,
  ``,
].join(`\n`)}`;

// The test environment pins these settings to their Yarn 4 values; the
// lockfile migration only kicks in for settings the user hasn't defined.
const WITH_YARN6_DEFAULTS = {
  env: {
    YARN_ENABLE_SCRIPTS: undefined,
    YARN_APPROVED_GIT_REPOSITORIES: undefined,
    YARN_NPM_MINIMAL_AGE_GATE: undefined,
  },
};

describe(`Features`, () => {
  describe(`V1 Migration`, () => {
    for (const command of [`install`, `dedupe`]) {
      test(
        `it should enable the node-modules linker when migrating from v1 (${command})`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `1.0.0`,
          },
        }, async ({path, run, source}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n\n`);

          await run(command);

          await expect(xfs.existsPromise(ppath.join(path, Filename.nodeModules, `no-deps`))).resolves.toEqual(true);
          await expect(xfs.readFilePromise(ppath.join(path, Filename.rc), `utf8`)).resolves.toContain(`nodeLinker: node-modules`);
        }),
      );
    }

    test(
      `it shouldn't override the linker when the project already configures one`,
      makeTemporaryEnv({
        dependencies: {
          [`no-deps`]: `1.0.0`,
        },
      }, async ({path, run, source}) => {
        await xfs.writeFilePromise(ppath.join(path, Filename.rc), `nodeLinker: pnp\n`);
        await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), V1_HEADER);

        await run(`install`);

        await expect(xfs.existsPromise(ppath.join(path, Filename.nodeModules, `no-deps`))).resolves.toEqual(false);
        await expect(xfs.readFilePromise(ppath.join(path, Filename.rc), `utf8`)).resolves.toEqual(`nodeLinker: pnp\n`);
      }),
    );

    test(
      `it should keep the versions of transitive dependencies, and write a regular lockfile`,
      makeTemporaryEnv({
        dependencies: {
          [`one-range-dep`]: `^1.0.0`,
        },
      }, async ({path, run, source}) => {
        // A fresh install would resolve no-deps@^1.0.0 to 1.1.0
        await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), `${V1_HEADER}${[
          `one-range-dep@^1.0.0:`,
          `  version "1.0.0"`,
          `  resolved "https://registry.yarnpkg.com/one-range-dep/-/one-range-dep-1.0.0.tgz#0000000000000000000000000000000000000000"`,
          `  dependencies:`,
          `    no-deps "^1.0.0"`,
          ``,
          `no-deps@^1.0.0:`,
          `  version "1.0.0"`,
          `  resolved "https://registry.yarnpkg.com/no-deps/-/no-deps-1.0.0.tgz#0000000000000000000000000000000000000000"`,
          ``,
        ].join(`\n`)}`);

        await run(`install`);

        await expect(source(`require('one-range-dep/package.json').version`)).resolves.toEqual(`1.0.0`);
        await expect(source(`require('one-range-dep').dependencies['no-deps'].version`)).resolves.toEqual(`1.0.0`);

        const lockfile = await xfs.readJsonPromise(ppath.join(path, Filename.lockfile));
        expect(lockfile.entries[`no-deps@npm:^1.0.0`].resolution.resolution).toEqual(`no-deps@npm:1.0.0`);

        // The migrated lockfile is now stable
        await run(`install`, `--immutable`);
      }),
    );

    test(
      `it should import scoped packages`,
      makeTemporaryEnv({
        dependencies: {
          [`@scoped/no-deps`]: `^1.0.0`,
        },
      }, async ({path, run, source}) => {
        await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), `${V1_HEADER}${[
          `"@scoped/no-deps@^1.0.0":`,
          `  version "1.0.0"`,
          `  resolved "https://registry.yarnpkg.com/@scoped/no-deps/-/no-deps-1.0.0.tgz#0000000000000000000000000000000000000000"`,
          ``,
        ].join(`\n`)}`);

        await run(`install`);

        await expect(source(`require('@scoped/no-deps')`)).resolves.toMatchObject({
          name: `@scoped/no-deps`,
          version: `1.0.0`,
        });
      }),
    );

    test(
      `it should import entries shared by multiple ranges`,
      makeTemporaryEnv({
        dependencies: {
          [`no-deps`]: `^1.0.0`,
          [`one-range-dep`]: `1.0.0`,
        },
      }, async ({path, run, source}) => {
        await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), `${V1_HEADER}${[
          `one-range-dep@1.0.0:`,
          `  version "1.0.0"`,
          `  resolved "https://registry.yarnpkg.com/one-range-dep/-/one-range-dep-1.0.0.tgz#0000000000000000000000000000000000000000"`,
          `  dependencies:`,
          `    no-deps "^1.0.0"`,
          ``,
          `no-deps@^1.0.0, no-deps@^1.0.1:`,
          `  version "1.0.1"`,
          `  resolved "https://registry.yarnpkg.com/no-deps/-/no-deps-1.0.1.tgz#0000000000000000000000000000000000000000"`,
          ``,
        ].join(`\n`)}`);

        await run(`install`);

        await expect(source(`require('no-deps')`)).resolves.toMatchObject({
          version: `1.0.1`,
        });

        await expect(source(`require('one-range-dep').dependencies['no-deps'].version`)).resolves.toEqual(`1.0.1`);
      }),
    );

    test(
      `it should import entries locked from other registries, and report them`,
      makeTemporaryEnv({
        dependencies: {
          [`no-deps`]: `^1.0.0`,
        },
      }, async ({path, run, source}) => {
        await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), `${V1_HEADER}${[
          `no-deps@^1.0.0:`,
          `  version "1.0.1"`,
          `  resolved "https://npm.example.com/no-deps/-/no-deps-1.0.1.tgz#0000000000000000000000000000000000000000"`,
          ``,
        ].join(`\n`)}`);

        const {stdout} = await run(`install`);

        expect(stdout).toContain(`Some packages were locked from npm.example.com`);

        await expect(source(`require('no-deps')`)).resolves.toMatchObject({
          version: `1.0.1`,
        });
      }),
    );

    test(
      `it should import entries whose tarball url has a query string`,
      makeTemporaryEnv({
        dependencies: {
          [`no-deps`]: `^1.0.0`,
        },
      }, async ({path, run, source}) => {
        // As written by mirrors such as Taobao; a fresh install would pick 1.1.0
        await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), `${V1_HEADER}${[
          `no-deps@^1.0.0:`,
          `  version "1.0.0"`,
          `  resolved "https://registry.npmmirror.com/no-deps/-/no-deps-1.0.0.tgz?cache=0&sync_timestamp=1600000000000#0000000000000000000000000000000000000000"`,
          ``,
        ].join(`\n`)}`);

        const {stdout} = await run(`install`);

        expect(stdout).not.toContain(`Can't import this entry`);

        await expect(source(`require('no-deps')`)).resolves.toMatchObject({
          version: `1.0.0`,
        });
      }),
    );

    test(
      `it should resolve again the entries it can't import, and report them`,
      makeTemporaryEnv({
        dependencies: {
          [`no-deps`]: `^1.0.0`,
        },
      }, async ({path, run, source}) => {
        // The tarball of an arbitrary url, for example because of a v1 `resolutions` override
        await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), `${V1_HEADER}${[
          `no-deps@^1.0.0:`,
          `  version "1.0.0"`,
          `  resolved "https://example.com/some-tarball.tgz"`,
          ``,
        ].join(`\n`)}`);

        const {stdout} = await run(`install`);

        expect(stdout).toMatch(/no-deps@npm:\^1\.0\.0.*Can't import this entry from the Yarn Classic lockfile/);

        await expect(source(`require('no-deps')`)).resolves.toMatchObject({
          version: `1.1.0`,
        });
      }),
    );

    test(
      `it should refuse to migrate the lockfile during immutable installs`,
      makeTemporaryEnv({
        dependencies: {
          [`no-deps`]: `^1.0.0`,
        },
      }, async ({path, run, source}) => {
        const v1Lockfile = `${V1_HEADER}${[
          `no-deps@^1.0.0:`,
          `  version "1.0.0"`,
          `  resolved "https://registry.yarnpkg.com/no-deps/-/no-deps-1.0.0.tgz#0000000000000000000000000000000000000000"`,
          ``,
        ].join(`\n`)}`;

        await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), v1Lockfile);

        await expect(run(`install`, `--immutable`)).rejects.toMatchObject({
          code: 1,
          stdout: expect.stringContaining(`The lockfile was generated by Yarn Classic (1.x); migrating it requires an install without --immutable`),
        });

        await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(v1Lockfile);
        await expect(xfs.existsPromise(ppath.join(path, Filename.rc))).resolves.toEqual(false);
      }),
    );

    describe(`Migration rules`, () => {
      test(
        `dedupe checks should apply Classic defaults without writing project files`,
        makeTemporaryEnv({
          dependencies: {
            [`release-date`]: `1.1.1`,
          },
        }, async ({path, run}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), V1_HEADER);

          await run(`dedupe`, `--check`, WITH_YARN6_DEFAULTS);

          await expect(xfs.existsPromise(ppath.join(path, Filename.rc))).resolves.toEqual(false);
          await expect(xfs.existsPromise(ppath.join(path, Filename.nodeModules))).resolves.toEqual(false);
          await expect(xfs.existsPromise(ppath.join(path, `.pnp.cjs`))).resolves.toEqual(false);
          await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(V1_HEADER);
        }),
      );

      test(
        `it should write the settings that preserve the behaviour of a Yarn Classic project and report them`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run}) => {
          const rcPath = ppath.join(path, Filename.rc);

          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), V1_NO_DEPS_LOCKFILE);

          const {stdout} = await run(`install`, WITH_YARN6_DEFAULTS);

          await expect(xfs.readFilePromise(rcPath, `utf8`)).resolves.toEqual([
            `approvedGitRepositories:\n`,
            `  - "**"\n`,
            `enableScripts: true\n`,
            `nodeLinker: node-modules\n`,
            `npmMinimalAgeGate: 0s\n`,
          ].join(``));

          expect(stdout).toContain(`The lockfile was generated by Yarn Classic (1.x); the following settings have been added to .yarnrc.yml to preserve its behaviour:`);
          expect(stdout).toContain(`nodeLinker: node-modules (Yarn Classic projects expect a node_modules folder)`);
          expect(stdout).toContain(`approvedGitRepositories: ["**"]`);
          expect(stdout).toContain(`enableScripts: true`);
          expect(stdout).toContain(`npmMinimalAgeGate: 0s`);

          // The lockfile has been rewritten, so the migration only happens once
          const {stdout: secondStdout} = await run(`install`, WITH_YARN6_DEFAULTS);
          expect(secondStdout).toContain(`All dependencies are up-to-date`);
          expect(secondStdout).not.toContain(`Yarn Classic`);
        }),
      );

      test(
        `it should apply the settings to the install that performs the migration`,
        makeTemporaryEnv({
          dependencies: {
            [`no-prepack`]: tests.startPackageServer().then(url => `${url}/repositories/no-prepack.git`),
            [`no-deps-scripted`]: `1.0.0`,
            [`release-date`]: `1.1.1`,
          },
        }, async ({path, run, source}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), V1_HEADER);

          await run(`install`, WITH_YARN6_DEFAULTS);

          await expect(xfs.existsPromise(ppath.join(path, Filename.nodeModules, `no-deps-scripted`))).resolves.toEqual(true);

          await expect(source(`require('no-prepack')`, WITH_YARN6_DEFAULTS)).resolves.toEqual(42);
          await expect(source(`require('no-deps-scripted/log')`, WITH_YARN6_DEFAULTS)).resolves.toEqual([`preinstall`, `install`, `postinstall`]);
          await expect(source(`require('release-date/package.json').version`, WITH_YARN6_DEFAULTS)).resolves.toEqual(`1.1.1`);
        }),
      );

      test(
        `it should leave the settings defined in the project rc, the home rc, or the environment untouched`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), V1_NO_DEPS_LOCKFILE);
          await xfs.writeFilePromise(ppath.join(path, Filename.rc), `enableScripts: false\n`);
          await xfs.writeFilePromise(ppath.join(ppath.dirname(path), Filename.rc), `approvedGitRepositories: []\n`);

          const {stdout} = await run(`install`, {
            env: {
              ...WITH_YARN6_DEFAULTS.env,
              YARN_NODE_LINKER: `pnp`,
            },
          });

          await expect(xfs.readFilePromise(ppath.join(path, Filename.rc), `utf8`)).resolves.toEqual(`enableScripts: false\nnpmMinimalAgeGate: 0s\n`);
          await expect(xfs.readFilePromise(ppath.join(ppath.dirname(path), Filename.rc), `utf8`)).resolves.toEqual(`approvedGitRepositories: []\n`);
          await expect(xfs.existsPromise(ppath.join(path, Filename.nodeModules, `no-deps`))).resolves.toEqual(false);

          expect(stdout).not.toContain(`nodeLinker`);
          expect(stdout).not.toContain(`enableScripts`);
          expect(stdout).not.toContain(`approvedGitRepositories`);
        }),
      );

      test(
        `it should still refuse to migrate during immutable installs`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), V1_NO_DEPS_LOCKFILE);

          const error = await run(`install`, `--immutable`, WITH_YARN6_DEFAULTS).catch(error => error);

          expect(error).toMatchObject({
            code: 1,
            stdout: expect.stringContaining(`The lockfile was generated by Yarn Classic (1.x); migrating it requires an install without --immutable`),
          });

          // The dedicated error is enough; no need to list the settings too
          expect(error.stdout).not.toContain(`immutable installs prevent writing them`);

          await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(V1_NO_DEPS_LOCKFILE);
          await expect(xfs.existsPromise(ppath.join(path, Filename.rc))).resolves.toEqual(false);
        }),
      );

      test(
        `it should apply the settings without writing them under the migration mode`,
        makeTemporaryEnv({
          dependencies: {
            [`no-deps`]: `^1.0.0`,
          },
        }, async ({path, run, source}) => {
          await xfs.writeFilePromise(ppath.join(path, Filename.lockfile), V1_NO_DEPS_LOCKFILE);

          // TODO: the migration mode doesn't create the folder of its lockfile yet
          await xfs.mkdirPromise(ppath.join(path, `.yarn/ignore/migration`), {recursive: true});

          const migrationEnv = {
            env: {
              ...WITH_YARN6_DEFAULTS.env,
              YARN_ENABLE_MIGRATION_MODE: `1`,
            },
          };

          const {stdout} = await run(`install`, migrationEnv);
          expect(stdout).toContain(`The lockfile was generated by Yarn Classic (1.x); the following settings are used during the migration but won't be written to .yarnrc.yml`);

          await expect(xfs.existsPromise(ppath.join(path, Filename.nodeModules, `no-deps`))).resolves.toEqual(true);
          await expect(source(`require('no-deps')`, migrationEnv)).resolves.toMatchObject({
            version: `1.0.0`,
          });

          await expect(xfs.existsPromise(ppath.join(path, Filename.rc))).resolves.toEqual(false);
          await expect(xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`)).resolves.toEqual(V1_NO_DEPS_LOCKFILE);

          await expect(run(`install`, migrationEnv)).resolves.toMatchObject({
            stdout: expect.stringContaining(`All dependencies are up-to-date`),
          });
        }),
      );
    });
  });
});
