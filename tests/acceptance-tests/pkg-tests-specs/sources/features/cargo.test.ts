import {Filename, PortablePath, ppath, xfs} from '@yarnpkg/fslib';
import {yarn}                               from 'pkg-tests-core';

// These tests stick to crates living in the project, which don't need a
// registry; resolving and fetching published crates is covered by the
// `rust` e2e test.

async function writeFiles(path: PortablePath, files: Record<string, string>) {
  for (const [rel, content] of Object.entries(files)) {
    const target = ppath.join(path, rel as PortablePath);

    await xfs.mkdirPromise(ppath.dirname(target), {recursive: true});
    await xfs.writeFilePromise(target, content);
  }
}

async function setupCargoProject(path: PortablePath, files: Record<string, string> = {}) {
  await yarn.writeConfiguration(path, {
    unstableIslands: {
      rust: {workspaces: [`root`], linker: `cargo`},
    },
  });

  await writeFiles(path, {
    [`Cargo.toml`]: [
      `[workspace]`,
      `members = ["crates/*"]`,
      ``,
      `[workspace.package]`,
      `version = "0.1.0"`,
      ``,
      `[workspace.dependencies]`,
      `lib = { path = "crates/lib" }`,
      ``,
    ].join(`\n`),
    [`crates/app/Cargo.toml`]: [
      `[package]`,
      `name = "app"`,
      `version.workspace = true`,
      ``,
      `[dependencies]`,
      `lib = { workspace = true }`,
      ``,
    ].join(`\n`),
    [`crates/lib/Cargo.toml`]: [
      `[package]`,
      `name = "lib"`,
      `version = "0.2.0"`,
      ``,
    ].join(`\n`),
    ...files,
  });
}

const EXPECTED_CARGO_LOCK = [
  `# This file is automatically @generated by Cargo.`,
  `# It is not intended for manual editing.`,
  `version = 4`,
  ``,
  `[[package]]`,
  `name = "app"`,
  `version = "0.1.0"`,
  `dependencies = [`,
  ` "lib",`,
  `]`,
  ``,
  `[[package]]`,
  `name = "lib"`,
  `version = "0.2.0"`,
  ``,
].join(`\n`);

describe(`Features`, () => {
  describe(`Cargo`, () => {
    test(`it should generate what Cargo needs from the Cargo.toml of the island's workspaces`, makeTemporaryEnv({
      name: `root`,
    }, async ({path, run}) => {
      await setupCargoProject(path);
      await run(`install`);

      await expect(xfs.readFilePromise(ppath.join(path, `Cargo.lock`), `utf8`)).resolves.toEqual(EXPECTED_CARGO_LOCK);

      const config = await xfs.readFilePromise(ppath.join(path, `.cargo/config.toml`), `utf8`);
      expect(config).toContain(`[source.crates-io]\nreplace-with = "yarn-vendor"`);
      expect(config).toContain(`[source.yarn-vendor]\ndirectory = ".cargo/vendor"`);

      // The members of the Cargo workspace don't have to be Yarn workspaces
      const lockfile = JSON.parse(await xfs.readFilePromise(ppath.join(path, Filename.lockfile), `utf8`));

      expect(lockfile.islands.rust).toMatchObject({
        [`app@cargo:path+crates/app`]: {
          resolution: {
            resolution: `app@cargo:path+crates/app`,
            version: `0.1.0`,
            dependencies: {lib: `cargo:path+crates/lib`},
          },
        },
        [`lib@cargo:path+crates/lib`]: {
          resolution: {
            resolution: `lib@cargo:path+crates/lib`,
            version: `0.2.0`,
          },
        },
      });
    }));

    test(`it should keep installing the JavaScript dependencies of the island's workspaces`, makeTemporaryEnv({
      name: `root`,
      dependencies: {[`no-deps`]: `1.0.0`},
    }, async ({path, run, source}) => {
      await setupCargoProject(path);
      await run(`install`);

      await expect(source(`require('no-deps')`)).resolves.toMatchObject({name: `no-deps`, version: `1.0.0`});
      await expect(xfs.readFilePromise(ppath.join(path, `Cargo.lock`), `utf8`)).resolves.toEqual(EXPECTED_CARGO_LOCK);
    }));

    test(`it should leave the rest of the Cargo configuration untouched`, makeTemporaryEnv({
      name: `root`,
    }, async ({path, run}) => {
      const userConfig = `[alias]\nt = "test"\n`;

      await setupCargoProject(path, {[`.cargo/config.toml`]: userConfig});

      await run(`install`);
      const config = await xfs.readFilePromise(ppath.join(path, `.cargo/config.toml`), `utf8`);

      expect(config.startsWith(`${userConfig}\n# >>> yarn cargo island >>>\n`)).toEqual(true);

      // Installing again mustn't pile blocks up
      await run(`install`, `--force`);
      await expect(xfs.readFilePromise(ppath.join(path, `.cargo/config.toml`), `utf8`)).resolves.toEqual(config);
    }));

    test(`it should notice the changes made to Cargo.toml files`, makeTemporaryEnv({
      name: `root`,
    }, async ({path, run}) => {
      await setupCargoProject(path);
      await run(`install`);

      await expect(run(`install`)).resolves.toMatchObject({
        stdout: expect.stringContaining(`up-to-date`),
      });

      await writeFiles(path, {
        [`crates/lib/Cargo.toml`]: `[package]\nname = "lib"\nversion = "0.3.0"\n`,
      });

      await run(`install`);

      await expect(xfs.readFilePromise(ppath.join(path, `Cargo.lock`), `utf8`)).resolves.toEqual(EXPECTED_CARGO_LOCK.replace(`0.2.0`, `0.3.0`));
    }));

    test(`it should restore the artifacts Cargo needs when they're removed`, makeTemporaryEnv({
      name: `root`,
    }, async ({path, run}) => {
      await setupCargoProject(path);
      await run(`install`);

      await xfs.removePromise(ppath.join(path, `Cargo.lock`));
      await run(`install`);

      await expect(xfs.readFilePromise(ppath.join(path, `Cargo.lock`), `utf8`)).resolves.toEqual(EXPECTED_CARGO_LOCK);
    }));

    test(`it should report the island workspaces that don't have a Cargo.toml`, makeTemporaryEnv({
      name: `root`,
    }, async ({path, run}) => {
      await yarn.writeConfiguration(path, {
        unstableIslands: {
          rust: {workspaces: [`root`], linker: `cargo`},
        },
      });

      await expect(run(`install`)).rejects.toThrow(/doesn't have a Cargo\.toml/);
    }));

    test(`it should refuse the manifests it can't honor rather than install something else`, makeTemporaryEnv({
      name: `root`,
    }, async ({path, run}) => {
      await setupCargoProject(path);
      await xfs.appendFilePromise(ppath.join(path, `Cargo.toml`), `\n[patch.crates-io]\nlib = { path = "crates/lib" }\n`);

      await expect(run(`install`)).rejects.toThrow(/\[patch\] table, which the cargo linker doesn't support yet/);
    }));

    test(`it should refuse cargo dependencies outside of cargo islands`, makeTemporaryEnv({
      name: `root`,
      dependencies: {serde: `cargo:^1`},
    }, async ({run}) => {
      await expect(run(`install`)).rejects.toThrow(/crates are installed by the islands using the cargo linker/);
    }));
  });
});
