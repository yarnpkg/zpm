//! Import of Yarn Classic (1.x) lockfiles.
//!
//! Classic lockfiles don't contain enough information to be reused as-is
//! (no peer dependencies, no checksums compatible with ours, ...), but they
//! tell us which version each descriptor was locked to. We record those as
//! pinned resolutions (similar to what we do for legacy Berry lockfiles), so
//! the first install keeps the versions the project was locked to instead of
//! resolving everything to the latest versions available.

use std::{collections::BTreeMap, sync::LazyLock};

use regex::Regex;
use zpm_config::Configuration;
use zpm_primitives::{split_ident_and_selector, Descriptor, Ident, Locator, Range, RegistrySemverRange, RegistryTagRange, ShorthandReference};
use zpm_utils::{FromFileString, ToHumanString};

use crate::{
    error::Error,
    http_npm,
    lockfile::{Lockfile, LockfileEntry},
    resolvers::Resolution,
};

const CLASSIC_LOCKFILE_MARKER: &str = "# yarn lockfile v1";

/// Hosts serving the public npm registry; tarballs resolved from one of them
/// are equivalent to tarballs resolved from the other.
const PUBLIC_NPM_REGISTRY_HOSTS: &[&str] = &[
    "registry.npmjs.org",
    "registry.yarnpkg.com",
];

/// Whether the given lockfile content was generated by Yarn Classic.
pub fn is_classic_lockfile(data: &str) -> bool {
    data.lines()
        .take_while(|line| line.starts_with('#') || line.trim().is_empty())
        .any(|line| line.trim_end() == CLASSIC_LOCKFILE_MARKER)
}

#[derive(Debug, Default, PartialEq, Eq)]
struct ClassicLockfileEntry {
    keys: Vec<String>,
    version: Option<String>,
    resolved: Option<String>,
}

/// Reads a token from the beginning of the string, either a JSON-quoted
/// string or a bare word ending at the first space or comma.
fn read_token(input: &str) -> Option<(String, &str)> {
    if input.starts_with('"') {
        let mut escaped
            = false;

        for (index, c) in input.char_indices().skip(1) {
            match c {
                '\\' if !escaped => escaped = true,
                '"' if !escaped => {
                    let token: String
                        = serde_json::from_str(&input[..=index]).ok()?;

                    return Some((token, &input[index + 1..]));
                },
                _ => escaped = false,
            }
        }

        None
    } else {
        let end = input.find([' ', ','])
            .unwrap_or(input.len());

        if end == 0 {
            return None;
        }

        Some((input[..end].to_string(), &input[end..]))
    }
}

/// Parses the subset of the Classic lockfile format we need: the keys of each
/// top-level entry, and their `version` and `resolved` fields. Lines that
/// can't be parsed are ignored; the matching descriptors will simply be
/// resolved again.
fn parse_classic_lockfile(data: &str) -> Vec<ClassicLockfileEntry> {
    let mut entries
        = Vec::<ClassicLockfileEntry>::new();

    for line in data.lines() {
        let line
            = line.trim_end();

        if line.is_empty() || line.trim_start().starts_with('#') {
            continue;
        }

        if !line.starts_with(' ') {
            let Some(mut rest) = line.strip_suffix(':') else {
                continue;
            };

            let mut entry
                = ClassicLockfileEntry::default();

            while let Some((key, next)) = read_token(rest) {
                entry.keys.push(key);
                rest = next.trim_start_matches([',', ' ']);
            }

            entries.push(entry);
            continue;
        }

        // We only care about the fields directly attached to the entries
        let Some(field) = line.strip_prefix("  ").filter(|field| !field.starts_with(' ')) else {
            continue;
        };

        let Some(entry) = entries.last_mut() else {
            continue;
        };

        let Some((name, rest)) = read_token(field) else {
            continue;
        };

        let Some((value, _)) = read_token(rest.trim_start()) else {
            continue;
        };

        match name.as_str() {
            "version" => entry.version = Some(value),
            "resolved" => entry.resolved = Some(value),
            _ => {},
        }
    }

    entries
}

static NPM_TARBALL_PATTERNS: LazyLock<Vec<Regex>> = LazyLock::new(|| vec![
    // Regular npm registries; `/download/` is used by some mirrors (Taobao),
    // which also add a query string after the tarball name
    Regex::new(r"^https?://[^/]+/(?:[^/]+/)*(?:@.+(?:/|%2f))?(?<name>[^/]+)/(?:-|download)/(?<file>[^/?#]+)\.tgz(?:\?[^#]*)?(?:#|$)").unwrap(),
    // GitHub Packages
    Regex::new(r"^https://npm\.pkg\.github\.com/download/(?:@[^/]+)/(?:[^/]+)/(?:[^/]+)/(?:[0-9a-f]+)(?:#|$)").unwrap(),
    // FontAwesome
    Regex::new(r"^https://npm\.fontawesome\.com/(?:@[^/]+)/(?<name>[^/]+)/-/(?:[^/]+)/(?<file>[^/?#]+)\.tgz(?:\?[^#]*)?(?:#|$)").unwrap(),
    // JFrog Artifactory, which repeats the scope in the tarball path
    Regex::new(r"^https?://[^/]+/.*/(?<scope>@[^/]+)/(?<name>[^/]+)/-/(?<scope2>@[^/]+)/(?<file>[.\w-]+)\.tgz(?:\?[^#]*)?(?:#|$)").unwrap(),
    // Yarn Classic offline mirror
    Regex::new(r"^[^/]+\.tgz#[0-9a-f]+$").unwrap(),
]);

/// Whether the `resolved` field of an entry points to the tarball of the
/// given package on an npm registry (as opposed to a git repository or an
/// arbitrary tarball, for instance because of a `resolutions` override).
fn is_npm_tarball_url(resolved: &str, ident: &Ident) -> bool {
    NPM_TARBALL_PATTERNS.iter().any(|pattern| {
        let Some(captures) = pattern.captures(resolved) else {
            return false;
        };

        if let (Some(scope), Some(scope2)) = (captures.name("scope"), captures.name("scope2")) {
            if scope.as_str() != scope2.as_str() {
                return false;
            }
        }

        match (captures.name("name"), captures.name("file")) {
            (Some(name), Some(file))
                => name.as_str() == ident.name() && file.as_str().starts_with(&format!("{}-", name.as_str())),

            _
                => true,
        }
    })
}

fn url_host(url: &str) -> Option<String> {
    url::Url::parse(url).ok()?
        .host_str()
        .map(|host| host.to_string())
}

fn is_same_registry_host(a: &str, b: &str) -> bool {
    a == b || (PUBLIC_NPM_REGISTRY_HOSTS.contains(&a) && PUBLIC_NPM_REGISTRY_HOSTS.contains(&b))
}

/// Turns the range of a Classic lockfile key into the range Yarn uses for
/// npm dependencies, or `None` if it doesn't refer to the npm registry.
fn normalize_classic_range(selector: &str) -> Option<Range> {
    match Range::from_file_string(selector).ok()? {
        Range::AnonymousSemver(params) => Some(RegistrySemverRange {
            ident: None,
            range: params.range,
        }.into()),

        Range::AnonymousTag(params) => match Range::from_file_string(&format!("npm:{}", params.tag)).ok()? {
            Range::RegistryTag(tag_params) if tag_params.ident.is_none() => Some(RegistryTagRange {
                ident: None,
                tag: tag_params.tag,
            }.into()),

            _ => None,
        },

        range @ (Range::RegistrySemver(_) | Range::RegistryTag(_))
            => Some(range),

        _ => None,
    }
}

pub struct ClassicLockfileImport {
    pub lockfile: Lockfile,

    /// Number of descriptors that will keep the version they were locked to.
    pub pinned_count: usize,

    /// Messages to report to the user about the entries we couldn't import.
    pub warnings: Vec<String>,
}

/// Builds a lockfile that pins every npm descriptor of a Yarn Classic
/// lockfile to the version it was locked to. Other entries (git
/// dependencies, arbitrary tarballs, ...) aren't recorded and will be
/// resolved again by the install.
pub fn from_classic_lockfile(data: &str, config: &Configuration) -> Result<ClassicLockfileImport, Error> {
    let mut lockfile
        = Lockfile::new();

    lockfile.metadata.version = 1;

    let mut warnings
        = Vec::new();

    // The inner descriptors of aliases can also be listed as their own
    // entries; in case of conflict the regular entry wins
    let mut pinned
        = BTreeMap::<Descriptor, Locator>::new();
    let mut pinned_by_alias
        = BTreeMap::<Descriptor, Locator>::new();

    let mut foreign_registries
        = BTreeMap::<String, String>::new();

    for entry in parse_classic_lockfile(data) {
        for key in &entry.keys {
            let (name, selector)
                = split_ident_and_selector(key);

            let parsed = Ident::from_file_string(name).ok()
                .and_then(|ident| Some((ident, normalize_classic_range(selector?)?)));

            let Some((ident, range)) = parsed else {
                // Local dependencies are never locked, so there's nothing to report
                if !selector.is_some_and(|selector| selector.starts_with("file:") || selector.starts_with("link:") || selector.starts_with("portal:")) {
                    warnings.push(format!("{}: Can't import this entry from the Yarn Classic lockfile; it'll be resolved again", key.to_print_string()));
                }

                continue;
            };

            // Aliases (`foo@npm:bar@^1.0.0`) are resolved through their inner
            // descriptor (`bar@npm:^1.0.0`), so that's the one we must pin
            let (package_ident, alias_inner_range, semver_range): (Ident, Option<Range>, Option<zpm_semver::Range>) = match &range {
                Range::RegistrySemver(params) => (
                    params.ident.clone().unwrap_or_else(|| ident.clone()),
                    params.ident.is_some().then(|| RegistrySemverRange {ident: None, range: params.range.clone()}.into()),
                    Some(params.range.clone()),
                ),

                Range::RegistryTag(params) => (
                    params.ident.clone().unwrap_or_else(|| ident.clone()),
                    params.ident.is_some().then(|| RegistryTagRange {ident: None, tag: params.tag.clone()}.into()),
                    None,
                ),

                _ => unreachable!("normalize_classic_range only returns registry ranges"),
            };

            let descriptor
                = Descriptor::new(ident.clone(), range.clone());

            let version = entry.version.as_deref()
                .and_then(|version| zpm_semver::Version::from_file_string(version).ok())
                .filter(|version| semver_range.as_ref().map_or(true, |range| range.check(version)));

            let resolved
                = entry.resolved.as_deref()
                    .filter(|resolved| is_npm_tarball_url(resolved, &package_ident));

            let (Some(version), Some(resolved)) = (version, resolved) else {
                warnings.push(format!(
                    "{}: Can't import this entry from the Yarn Classic lockfile (resolved from {}); it'll be resolved again",
                    descriptor.to_print_string(),
                    entry.resolved.as_deref().unwrap_or("an unknown location").to_print_string(),
                ));

                continue;
            };

            // Yarn Classic stored the tarball urls in the lockfile, whereas we
            // always fetch the packages from the configured registry
            if let Some(resolved_host) = url_host(resolved) {
                let registry
                    = http_npm::get_registry_for_ident(config, Some(&package_ident), false)?;

                if url_host(registry).map_or(true, |registry_host| !is_same_registry_host(&resolved_host, &registry_host)) {
                    foreign_registries.entry(resolved_host)
                        .or_insert_with(|| registry.to_string());
                }
            }

            let locator
                = Locator::new(package_ident.clone(), ShorthandReference {version}.into());

            match alias_inner_range {
                Some(inner_range) => {
                    pinned_by_alias.entry(Descriptor::new(package_ident, inner_range))
                        .or_insert(locator);
                },

                None => {
                    pinned.insert(descriptor, locator);
                },
            }
        }
    }

    for (descriptor, locator) in pinned_by_alias {
        pinned.entry(descriptor)
            .or_insert(locator);
    }

    for (host, registry) in foreign_registries {
        warnings.push(format!(
            "Some packages were locked from {}, which isn't the registry Yarn is configured to use for them ({}); they'll be fetched from the configured registry (see the npmRegistryServer and npmScopes settings)",
            host.to_print_string(),
            registry.to_print_string(),
        ));
    }

    let pinned_count
        = pinned.len();

    for (descriptor, locator) in pinned {
        lockfile.entries.insert(locator.clone(), LockfileEntry {
            checksum: None,
            resolution: Resolution::new_empty(locator.clone(), Default::default()),
        });

        lockfile.resolutions.insert(descriptor, locator);
    }

    Ok(ClassicLockfileImport {
        lockfile,
        pinned_count,
        warnings,
    })
}

