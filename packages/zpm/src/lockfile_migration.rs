use zpm_config::{Configuration, NodeLinker, Setting, Settings, Source};
use zpm_parsers::{DataDocument, Value};
use zpm_utils::{DataType, IoResultExt, Path};

use crate::{
    error::Error,
    lockfile::legacy_berry_lockfile_version,
    lockfile_classic::is_classic_lockfile,
    project::{LOCKFILE_NAME, Project},
    report,
};

/// Berry writes the `__metadata` block right after a two-line header, and Yarn
/// Classic its version marker on the second line; we only need to read that
/// far to know which release wrote the lockfile.
const LOCKFILE_HEADER_SIZE: u64 = 4096;

/// The release that generated a lockfile we're migrating from.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LegacyLockfile {
    Classic,
    Berry(u64),
}

impl LegacyLockfile {
    pub fn from_header(header: &str) -> Option<LegacyLockfile> {
        if is_classic_lockfile(header) {
            return Some(LegacyLockfile::Classic);
        }

        legacy_berry_lockfile_version(header)
            .map(LegacyLockfile::Berry)
    }

    fn describe(&self) -> String {
        match self {
            LegacyLockfile::Classic
                => "The lockfile was generated by Yarn Classic (1.x)".to_string(),

            LegacyLockfile::Berry(version)
                => format!("The lockfile was generated by an older Yarn release (version {})", version),
        }
    }
}

/// Which lockfiles a migration rule applies to.
pub enum MigrationCriterion {
    /// Lockfiles generated by Yarn Classic.
    Classic,

    /// Lockfiles whose Berry version is strictly lower; Yarn Classic
    /// lockfiles predate all of them.
    BelowVersion(u64),
}

impl MigrationCriterion {
    pub fn matches(&self, lockfile: LegacyLockfile) -> bool {
        match (self, lockfile) {
            (MigrationCriterion::Classic, lockfile)
                => lockfile == LegacyLockfile::Classic,

            (MigrationCriterion::BelowVersion(_), LegacyLockfile::Classic)
                => true,

            (MigrationCriterion::BelowVersion(below_version), LegacyLockfile::Berry(version))
                => version < *below_version,
        }
    }
}

/// Yarn 5 and 6 ship with stricter defaults than Yarn 4, and Plug'n'Play has
/// been the default linker since Yarn 2. When we import a lockfile generated
/// by an older release, we pin the settings that would otherwise change
/// behaviour, the same way Berry's `yarn install` does (see
/// `LOCKFILE_MIGRATION_RULES` in Berry's `install.ts`).
pub struct LockfileMigrationRule {
    pub name: &'static str,
    pub env_name: &'static str,

    pub criterion: MigrationCriterion,

    /// What gets written in the rc file, and how it is displayed.
    pub value: fn() -> Value,
    pub display_value: &'static str,
    pub reason: &'static str,

    /// Applies the value to the configuration of the running install.
    pub apply: fn(&mut Settings, Source),
}

pub const LOCKFILE_MIGRATION_RULES: &[LockfileMigrationRule] = &[
    LockfileMigrationRule {
        name: "nodeLinker",
        env_name: "YARN_NODE_LINKER",
        criterion: MigrationCriterion::Classic,
        value: || Value::String("node-modules".to_string()),
        display_value: "node-modules",
        reason: "Yarn Classic projects expect a node_modules folder",
        apply: |settings, source| settings.node_linker.force(NodeLinker::NodeModules, source),
    },
    LockfileMigrationRule {
        name: "approvedGitRepositories",
        env_name: "YARN_APPROVED_GIT_REPOSITORIES",
        criterion: MigrationCriterion::BelowVersion(9),
        value: || Value::Array(vec![Value::String("**".to_string())]),
        display_value: "[\"**\"]",
        reason: "git dependencies used to be allowed from any repository",
        apply: |settings, source| settings.approved_git_repositories = vec![Setting::new("**".to_string(), source)],
    },
    LockfileMigrationRule {
        name: "enableScripts",
        env_name: "YARN_ENABLE_SCRIPTS",
        criterion: MigrationCriterion::BelowVersion(9),
        value: || Value::Bool(true),
        display_value: "true",
        reason: "dependency build scripts used to run by default",
        apply: |settings, source| settings.enable_scripts.force(true, source),
    },
    LockfileMigrationRule {
        name: "npmMinimalAgeGate",
        env_name: "YARN_NPM_MINIMAL_AGE_GATE",
        criterion: MigrationCriterion::BelowVersion(10),
        value: || Value::String("0s".to_string()),
        display_value: "0s",
        reason: "freshly published versions used to be installable right away",
        apply: |settings, source| settings.npm_minimal_age_gate.force(std::time::Duration::ZERO, source),
    },
];

pub struct LockfileMigration {
    pub lockfile: LegacyLockfile,
    pub rules: Vec<&'static LockfileMigrationRule>,
}

impl LockfileMigration {
    /// Returns the rules that apply to the project, if its root lockfile was
    /// generated by Yarn Classic or an older Berry release. Rules for
    /// settings the user already defined (in the project rc, the home rc, or
    /// the environment) are skipped.
    pub fn detect(config: &Configuration, project_cwd: &Path) -> Result<Option<LockfileMigration>, Error> {
        let Some(lockfile) = read_legacy_lockfile(&project_cwd.with_join_str(LOCKFILE_NAME))? else {
            return Ok(None);
        };

        let rc_documents
            = [&config.user_config_path, &config.project_config_path].into_iter()
                .flatten()
                .map(read_rc_document)
                .collect::<Result<Vec<_>, _>>()?;

        let rules
            = LOCKFILE_MIGRATION_RULES.iter()
                .filter(|rule| rule.criterion.matches(lockfile))
                .filter(|rule| !config.context.env.contains_key(rule.env_name))
                .filter(|rule| !rc_documents.iter().any(|document| document.get(rule.name).is_some()))
                .collect::<Vec<_>>();

        if rules.is_empty() {
            return Ok(None);
        }

        Ok(Some(LockfileMigration {
            lockfile,
            rules,
        }))
    }

    pub fn apply(&self, settings: &mut Settings, source: Source) {
        for rule in &self.rules {
            (rule.apply)(settings, source);
        }
    }

    /// Writes the settings into the project rc file, preserving its formatting
    /// (same writer as `yarn config set`).
    pub fn persist(&self, rc_path: &Path) -> Result<(), Error> {
        let mut document
            = rc_path
                .fs_read_text()
                .ok_missing()?
                .unwrap_or_default();

        for rule in &self.rules {
            document = DataDocument::update_document_field(
                &document,
                zpm_parsers::Path::from_segments(vec![rule.name.to_string()]),
                (rule.value)(),
            )?;
        }

        Configuration::validate(rc_path, &document)
            .map_err(|e| Error::ConfigurationParseError(Arc::new(e)))?;

        rc_path
            .fs_change(&document, false)?;

        Ok(())
    }

    fn report_rules(&self, report: &report::StreamReport) {
        for rule in &self.rules {
            report.info(format!(
                "  {}: {} ({})",
                DataType::Code.colorize(rule.name),
                DataType::Code.colorize(rule.display_value),
                rule.reason,
            ));
        }
    }
}

/// Applies the lockfile migration rules to the install about to run. Outside
/// of migration mode and immutable installs the settings are also persisted
/// into the project rc file; the legacy lockfile is then replaced by the new
/// format, so this only ever happens once.
///
/// Must run before anything reads the settings it may change (linker, git
/// approvals, age gate, build scripts).
pub fn migrate_legacy_lockfile_settings(project: &mut Project) -> Result<(), Error> {
    let Some(migration) = LockfileMigration::detect(&project.config, &project.project_cwd)? else {
        return Ok(());
    };

    let rc_path
        = project.config.project_config_path.clone()
            .expect("A project always has a project rc path");

    let rc_name
        = rc_path.basename()
            .unwrap_or_default()
            .to_string();

    let settings
        = &project.config.settings;

    if settings.enable_migration_mode.value {
        // Already applied when the project got loaded; the root lockfile is
        // still used by the regular Yarn release, so we leave the rc alone.
        report::if_active(|report| {
            report.info(format!(
                "{}; the following settings are used during the migration but won't be written to {}:",
                migration.lockfile.describe(),
                DataType::Path.colorize(&rc_name),
            ));

            migration.report_rules(report);
        });

        return Ok(());
    }

    if settings.enable_immutable_installs.value {
        // Immutable installs can't import Yarn Classic lockfiles at all, and
        // report it with a dedicated error once they read the lockfile
        if migration.lockfile == LegacyLockfile::Classic {
            return Ok(());
        }

        let source
            = settings.enable_immutable_installs.source;

        migration.apply(&mut project.config.settings, source);

        report::if_active(|report| {
            report.warn(format!(
                "{}; the following settings are needed to preserve its behaviour, but immutable installs prevent writing them to {}:",
                migration.lockfile.describe(),
                DataType::Path.colorize(&rc_name),
            ));

            migration.report_rules(report);
        });

        return Ok(());
    }

    migration.persist(&rc_path)?;
    migration.apply(&mut project.config.settings, Source::Project);

    // The rc file is an input of the install; account for our own write so
    // that the next command doesn't see it as a change made after the install.
    let rc_modified_at
        = rc_path.fs_metadata()?
            .modified()?
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos();

    project.last_modified_at.update(rc_modified_at);

    report::if_active(|report| {
        report.info(format!(
            "{}; the following settings have been added to {} to preserve its behaviour:",
            migration.lockfile.describe(),
            DataType::Path.colorize(&rc_name),
        ));

        migration.report_rules(report);

        report.info("Remove them from the file to opt into the new defaults.".to_string());
    });

    Ok(())
}

fn read_legacy_lockfile(lockfile_path: &Path) -> Result<Option<LegacyLockfile>, Error> {
    let file = match std::fs::File::open(lockfile_path.to_path_buf()) {
        Ok(file) => file,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(err) => return Err(err.into()),
    };

    let mut header
        = Vec::new();

    file.take(LOCKFILE_HEADER_SIZE)
        .read_to_end(&mut header)?;

    Ok(LegacyLockfile::from_header(&String::from_utf8_lossy(&header)))
}

fn read_rc_document(rc_path: &Path) -> Result<serde_yaml::Mapping, Error> {
    let Some(content) = rc_path.fs_read_text().ok_missing()? else {
        return Ok(serde_yaml::Mapping::new());
    };

    let document: Option<serde_yaml::Mapping>
        = serde_yaml::from_str(&content)
            .map_err(|e| Error::ConfigurationParseError(Arc::new(e)))?;

    Ok(document.unwrap_or_default())
}

#[cfg(test)]
mod tests {
    use super::{LOCKFILE_MIGRATION_RULES, LegacyLockfile};

    fn rule_names(lockfile: LegacyLockfile) -> Vec<&'static str> {
        LOCKFILE_MIGRATION_RULES.iter()
            .filter(|rule| rule.criterion.matches(lockfile))
            .map(|rule| rule.name)
            .collect()
    }

    #[test]
    fn detects_legacy_lockfiles_from_their_header() {
        assert_eq!(LegacyLockfile::from_header("# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n"), Some(LegacyLockfile::Classic));
        assert_eq!(LegacyLockfile::from_header("# This file is generated by running \"yarn install\" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 8\n  cacheKey: 10c0\n"), Some(LegacyLockfile::Berry(8)));
        assert_eq!(LegacyLockfile::from_header("{\n  \"__metadata\": {\n    \"version\": 10\n  }\n}\n"), None);
    }

    #[test]
    fn applies_every_rule_to_classic_lockfiles() {
        assert_eq!(rule_names(LegacyLockfile::Classic), vec!["nodeLinker", "approvedGitRepositories", "enableScripts", "npmMinimalAgeGate"]);
    }

    #[test]
    fn applies_the_rules_older_than_berry_lockfiles() {
        assert_eq!(rule_names(LegacyLockfile::Berry(4)), vec!["approvedGitRepositories", "enableScripts", "npmMinimalAgeGate"]);
        assert_eq!(rule_names(LegacyLockfile::Berry(8)), vec!["approvedGitRepositories", "enableScripts", "npmMinimalAgeGate"]);
        assert_eq!(rule_names(LegacyLockfile::Berry(9)), vec!["npmMinimalAgeGate"]);
        assert!(rule_names(LegacyLockfile::Berry(10)).is_empty());
    }
}
