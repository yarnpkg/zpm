use std::{env, fs, path::PathBuf};

use ts_rs::{Config, TS};
use zpm::daemon::{
    AttachedLongLivedTask, BufferedOutputLine, DaemonMessage, DaemonMeta, DaemonNotification,
    DaemonRequest, DaemonRequestEnvelope, DaemonResponse, DeclaredTaskInfo, LongLivedTaskInfo,
    LongLivedTaskStatus, SubscriptionScope, TaskEvent, TaskEventState, TaskSubscription,
    TaskfileError,
};

const DEFAULT_OUTPUT_PATH: &str = "packages/zpm/src/daemon/protocol.generated.ts";

fn usage() -> String {
    format!(
        "Usage: cargo run -p zpm --bin generate_daemon_types [--check] [--output <path>]\n\
         \n\
         Options:\n\
           --check           Verify the generated file is up to date.\n\
           --output <path>   Output path (default: {DEFAULT_OUTPUT_PATH}).\n"
    )
}

fn parse_args() -> Result<(bool, PathBuf), String> {
    let mut check = false;
    let mut output_path = PathBuf::from(DEFAULT_OUTPUT_PATH);
    let mut args = env::args().skip(1);

    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--check" => check = true,
            "--output" => {
                let Some(path) = args.next() else {
                    return Err(format!("Missing value for --output\n\n{}", usage()));
                };

                output_path = PathBuf::from(path);
            }
            "--help" | "-h" => {
                return Err(usage());
            }
            other => {
                return Err(format!("Unknown argument: {other}\n\n{}", usage()));
            }
        }
    }

    Ok((check, output_path))
}

fn to_exported_declaration<T: TS>(config: &Config) -> String {
    let decl = T::decl(config);
    let mut out = String::new();

    for line in decl.lines() {
        if line.starts_with("export ") {
            out.push_str(line);
        } else if line.starts_with("type ") || line.starts_with("interface ") {
            out.push_str("export ");
            out.push_str(line);
        } else {
            out.push_str(line);
        }

        out.push('\n');
    }

    out
}

fn render() -> String {
    let config = Config::default();
    let mut out = String::new();
    out.push_str("// This file is generated by `cargo run -p zpm --bin generate_daemon_types`.\n");
    out.push_str("// Do not edit by hand.\n\n");

    for decl in [
        to_exported_declaration::<TaskSubscription>(&config),
        to_exported_declaration::<SubscriptionScope>(&config),
        to_exported_declaration::<DaemonRequestEnvelope>(&config),
        to_exported_declaration::<DaemonRequest>(&config),
        to_exported_declaration::<BufferedOutputLine>(&config),
        to_exported_declaration::<AttachedLongLivedTask>(&config),
        to_exported_declaration::<DaemonMeta>(&config),
        to_exported_declaration::<LongLivedTaskStatus>(&config),
        to_exported_declaration::<TaskEventState>(&config),
        to_exported_declaration::<TaskEvent>(&config),
        to_exported_declaration::<DeclaredTaskInfo>(&config),
        to_exported_declaration::<TaskfileError>(&config),
        to_exported_declaration::<LongLivedTaskInfo>(&config),
        to_exported_declaration::<DaemonResponse>(&config),
        to_exported_declaration::<DaemonNotification>(&config),
        to_exported_declaration::<DaemonMessage>(&config),
    ] {
        out.push_str(&decl);
        out.push('\n');
    }

    out
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let (check, output_path) = match parse_args() {
        Ok(parsed) => parsed,
        Err(msg) => {
            eprintln!("{msg}");
            std::process::exit(1);
        }
    };

    let generated = render();

    if check {
        let existing = fs::read_to_string(&output_path).unwrap_or_default();

        if existing != generated {
            eprintln!(
                "Generated daemon types are out of date.\nRun: cargo run -p zpm --bin generate_daemon_types"
            );
            std::process::exit(1);
        }

        println!("Daemon types are up to date: {}", output_path.display());
        return Ok(());
    }

    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent)?;
    }

    fs::write(&output_path, generated)?;
    println!("Generated {}", output_path.display());

    Ok(())
}
